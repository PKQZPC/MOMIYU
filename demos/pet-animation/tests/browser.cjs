const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const moduleRoot = process.env.MOMIYU_QA_MODULES;
if (!moduleRoot) throw new Error('Set MOMIYU_QA_MODULES to the installed runtime node_modules directory.');
const { chromium } = require(path.join(moduleRoot, 'playwright'));
const root = path.resolve(__dirname, '..');
const output = path.join(root, '.local'); fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.MOMIYU_BROWSER ? { executablePath: process.env.MOMIYU_BROWSER } : process.platform === 'win32' ? { channel: 'msedge' } : {}) });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
    const page = await context.newPage(); const errors = [], remoteRequests = [];
    page.on('pageerror', e => errors.push(String(e)));
    page.on('request', req => { if (/^https?:/.test(req.url())) remoteRequests.push(req.url()); });
    await page.clock.install();
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
    await page.waitForFunction(() => window.momiyuDemo?.assetsReady);
    await page.clock.runFor(500);
    await page.screenshot({ path: path.join(output, 'idle.png'), fullPage: true });
    await page.click('#greet'); await page.clock.runFor(450);
    assert.equal(await page.evaluate(() => momiyuDemo.bodyPose), 2);
    await page.screenshot({ path: path.join(output, 'wave.png'), fullPage: true });
    await page.clock.runFor(1000);
    await page.click('#look'); await page.clock.runFor(650);
    assert.equal(await page.evaluate(() => momiyuDemo.bodyPose), 4);
    await page.screenshot({ path: path.join(output, 'look.png'), fullPage: true });
    await page.clock.runFor(1700);
    await page.click('#stretch'); await page.clock.runFor(650);
    assert.equal(await page.evaluate(() => momiyuDemo.bodyPose), 5);
    await page.screenshot({ path: path.join(output, 'stretch.png'), fullPage: true });
    await page.clock.runFor(1700);
    await page.click('#rest'); await page.clock.runFor(1500);
    assert.equal(await page.evaluate(() => momiyuDemo.state.mode), 'sleeping');
    assert.equal(await page.evaluate(() => momiyuDemo.state.lastResult), null);
    await page.screenshot({ path: path.join(output, 'sleep.png'), fullPage: true });
    await page.locator('#pet-canvas').focus(); await page.keyboard.press('Enter'); await page.clock.runFor(1400);
    assert.equal(await page.evaluate(() => momiyuDemo.state.mode), 'idle');
    await page.click('[data-skill="literature"]'); await page.clock.runFor(800);
    assert.equal(await page.evaluate(() => momiyuDemo.state.mode), 'activating');
    await page.screenshot({ path: path.join(output, 'literature.png'), fullPage: true });
    await page.clock.runFor(1200);
    assert.equal(await page.evaluate(() => momiyuDemo.state.mode), 'working');
    await page.click('#cancel-task'); await page.clock.runFor(9000);
    assert.equal(await page.evaluate(() => momiyuDemo.state.lastResult.result), 'canceled');
    await page.click('[data-skill="garden"]'); await page.clock.runFor(800);
    await page.screenshot({ path: path.join(output, 'garden.png'), fullPage: true });
    await page.clock.runFor(6500);
    assert.equal(await page.evaluate(() => momiyuDemo.state.mode), 'completed');
    await page.clock.runFor(2500);
    await page.selectOption('#outcome', 'failed'); await page.click('[data-skill="literature"]'); await page.clock.runFor(7300);
    assert.equal(await page.evaluate(() => momiyuDemo.state.mode), 'failed');
    await page.screenshot({ path: path.join(output, 'failed.png'), fullPage: true });
    await page.clock.runFor(2500); await page.selectOption('#outcome', 'partial');
    await page.click('[data-skill="garden"]'); await page.clock.runFor(7300);
    assert.equal(await page.evaluate(() => momiyuDemo.state.mode), 'partial');
    await page.click('#reset'); await page.click('#tour'); await page.clock.runFor(1200);
    await page.click('#reset'); await page.clock.runFor(35000);
    assert.equal(await page.evaluate(() => momiyuDemo.state.mode), 'idle');
    assert.equal(await page.evaluate(() => momiyuDemo.state.lastResult), null);
    await page.setViewportSize({ width: 390, height: 844 }); await page.clock.runFor(100);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    assert.deepEqual(errors, []); assert.deepEqual(remoteRequests, []);
    await context.close();
    const quietContext = await browser.newContext({ reducedMotion: 'reduce', viewport: { width: 1280, height: 900 } });
    const quietPage = await quietContext.newPage(); await quietPage.goto(pathToFileURL(path.join(root, 'index.html')).href);
    await quietPage.waitForFunction(() => window.momiyuDemo?.assetsReady);
    assert.equal(await quietPage.evaluate(() => momiyuDemo.reducedMotion), true);
    await quietContext.close();
    console.log(JSON.stringify({ browser: 'chromium', passed: ['wave pose', 'head and ear pose', 'body stretch pose', 'rest without work', 'keyboard wake', 'distinct activations', 'cancel stale callbacks', 'completed', 'failed', 'partial', 'tour interruption', '390px overflow', 'reduced motion', 'no page errors', 'no network requests'], screenshots: output }));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
