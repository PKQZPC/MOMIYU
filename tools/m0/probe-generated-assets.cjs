// Read-only PNG inspection, pack assembly by byte copying, headless runtime fixture.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {createHash}=require('node:crypto');
const {readPack,installPack}=require('./reuse/character-pack.cjs');
const qa=process.env.MOMIYU_QA_MODULES;
if(!qa)throw new Error('Set MOMIYU_QA_MODULES.');
const {PNG}=require(path.join(qa,'pngjs'));
const {chromium}=require(path.join(qa,'playwright'));
const root=path.resolve(__dirname,'../..');
const out=path.join(__dirname,'.local/image-validation-20261030');
const records={},checks=[];
function inspect(name){
 const bytes=fs.readFileSync(path.join(out,name+'.png')),png=PNG.sync.read(bytes);
 let clear=0,partial=0,opaque=0,border=0;
 for(let y=0;y<png.height;y++)for(let x=0;x<png.width;x++){
  const a=png.data[(y*png.width+x)*4+3];if(a===0)clear++;else if(a===255)opaque++;else partial++;
  if(a>=16&&(x===0||y===0||x===png.width-1||y===png.height-1))border++;
 }
 return {png,record:{file:name+'.png',width:png.width,height:png.height,requested_size:'1024x1024',size_matches_request:png.width===1024&&png.height===1024,clear,partial,opaque,nontransparent_border_pixels:border,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')}};
}
(async()=>{
 let browser;
 const report={schema_version:'0.1.0',synthetic_only:true,images:records,checks,status:'failed'};
 try{
  for(const name of ['baby','evolution','transparent'])records[name]=inspect(name).record;
  const {png}=inspect('transparent');
  assert.ok(records.transparent.clear>0&&records.transparent.opaque>0,'Genuine alpha and nonempty body required.');
  checks.push({name:'genuine PNG alpha and visible body',passed:true});
  const folder=path.join(out,'runtime-input');fs.mkdirSync(folder,{recursive:true});
  // Copy original generated bytes; do not locally remove background or edit the image.
  fs.copyFileSync(path.join(out,'transparent.png'),path.join(folder,'sprite.png'));
  fs.copyFileSync(path.join(out,'transparent.png'),path.join(folder,'preview.png'));
  fs.writeFileSync(path.join(folder,'character.json'),JSON.stringify({name:'M0 generated candidate (not published)',sprite:'sprite.png',preview:'preview.png',frame:{width:png.width,height:png.height},columns:1,states:{idle:{row:0,frames:1,interval:900,loop:true}}},null,2));
  const decode=bytes=>{try{const p=PNG.sync.read(bytes);return {width:p.width,height:p.height};}catch{return null;}};
  const pack=readPack(folder,decode);
  report.runtime_pack=pack.manifest;
  report.installed=path.basename(installPack(pack,path.join(out,'runtime-store'),decode));
  checks.push({name:'actual-size immutable pack validates and stages',passed:true});
  const payload={manifest:pack.manifest,images:{main:'data:image/png;base64,'+pack.files['sprite.png'].toString('base64')}};
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage();
  await page.route('**/*',route=>route.request().url().startsWith('file:')?route.continue():route.abort());
  await page.addInitScript(value=>{window.petBridge={readPack:async()=>value,hover:v=>{window.lastHover=v;}};},payload);
  await page.goto('file:///'+path.join(root,'tests/fixtures/m0/pet-reuse-window.html').replaceAll('\\','/'));
  await page.evaluate(()=>fixture.ready);
  const state=await page.evaluate(()=>fixture.snapshot());
  assert.equal(state.version,pack.manifest.id);assert.equal(state.alphaWidth,png.width);assert.equal(state.alphaHeight,png.height);assert.equal(state.nodeExposed,false);
  checks.push({name:'generated image decodes in isolated renderer using adapted player',passed:true});
  let solid;
  for(let y=8;y<png.height-8&&!solid;y+=8)for(let x=8;x<png.width-8;x+=8){
   // The returned image uses alpha 253 for most interior pixels; a visible
   // near-opaque interior is valid and does not have to equal byte 255.
   if([[-5,0],[5,0],[0,-5],[0,5],[0,0]].every(([dx,dy])=>png.data[((y+dy)*png.width+x+dx)*4+3]>=240)){solid={x,y};break;}
  }
  assert.ok(solid,'Solid interior sample required.');
  const point={x:state.rect.x+(solid.x+.5)*state.rect.width/png.width,y:state.rect.y+(solid.y+.5)*state.rect.height/png.height};
  await page.mouse.move(point.x,point.y);
  assert.equal(await page.evaluate(()=>window.lastHover),true);
  await page.mouse.move(1,1);assert.equal(await page.evaluate(()=>window.lastHover),false);
  checks.push({name:'actual generated alpha supports body hit and background passthrough',passed:true});
  const screenshot=await page.screenshot({omitBackground:true});fs.writeFileSync(path.join(out,'runtime-preview.png'),screenshot);
  const rendered=PNG.sync.read(screenshot);assert.equal(rendered.data[3],0);assert.ok(rendered.data.some((value,index)=>index%4===3&&value>0));
  checks.push({name:'runtime screenshot retains transparency and draws subject',passed:true});
  report.status='passed';
  report.quality_flags={touches_frame:records.transparent.nontransparent_border_pixels>0,ai_review:'See judgment.json; technical loading does not publish or certify visual quality.'};
 }catch(error){report.error=error.message;process.exitCode=1;}
 finally{
  if(browser)await browser.close();
  report.limits=['One generated idle frame, no generated motion or complete action package.','No live desktop overlay or pet publication; only an owned headless browser fixture.','Requested versus returned dimensions recorded separately.'];
  fs.writeFileSync(path.join(out,'runtime-check.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify({status:report.status,checks,error:report.error,quality_flags:report.quality_flags}));
 }
})();
